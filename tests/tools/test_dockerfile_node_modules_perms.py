"""contract test: Dockerfile keeps runtime node_modules trees writable

regression guard for #18800. the container drops privileges to the hermes
user in entrypoint.sh. Runtime opt-in setup flows can still update packages
under /opt/hermes/node_modules; after HERMES_UID/HERMES_GID remaps, stage2
grants hermes the old build GID so the tree must have group-write bits baked
into the image. This avoids a first-boot recursive chown over node_modules.
"""
from __future__ import annotations

from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
DOCKERFILE = REPO_ROOT / "Dockerfile"


def test_dockerfile_marks_runtime_node_modules_group_writable() -> None:
    text = DOCKERFILE.read_text()

    chmod_lines = [
        line for line in text.splitlines()
        if "chmod" in line or "g+rwX" in line
    ]
    assert chmod_lines, (
        "Dockerfile must mark runtime node_modules trees group-writable; "
        "see #18800 and the stage2 build-tree group repair"
    )

    chmod_block = "\n".join(chmod_lines)

    # Runtime-mutable trees must be passed to the group-write command.
    # /opt/hermes/web is intentionally excluded: it is build-time only,
    # because HERMES_WEB_DIST points at hermes_cli/web_dist for runtime.
    for required_path in (
        "/opt/hermes/ui-tui",
        "/opt/hermes/node_modules",
        "/opt/hermes/gateway",
    ):
        assert required_path in chmod_block, (
            f"{required_path} must be passed to the chmod -R g+rwX command "
            f"in the Dockerfile (see #18800, #27221)"
        )
